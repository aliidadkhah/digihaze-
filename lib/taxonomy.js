export function getTaxonomyEntry(type, value) {
  if (type === "flavor") return FLAVORS[value] || null;
  if (type === "nicotine") return NICOTINE_LEVELS[value] || null;
  return null;
}

// فیلد taxonomy ممکنه یک مقدار یا چند مقدار (جدا شده با کاما) باشه.
// مثلاً nicotine = "30mg,50mg" یعنی محصول هم ۳۰ و هم ۵۰ داره.
export function parseTaxonomyValues(raw) {
  return String(raw || "")
    .split(",")
    .map((v) => v.trim())
    .filter(Boolean);
}

// فقط مقدارهای معتبر، به ترتیب تعریف‌شده، به‌صورت رشته‌ی کاما-جدا
export function normalizeTaxonomyValues(type, raw) {
  const list = Array.isArray(raw) ? raw : parseTaxonomyValues(raw);
  const source = type === "nicotine" ? NICOTINE_LEVELS : FLAVORS;

  return Object.keys(source)
    .filter((id) => list.includes(id))
    .join(",");
}

export function hasTaxonomyValue(product, type, value) {
  const field = TAXONOMY_TYPES[type]?.field;
  if (!field || !product) return false;

  return parseTaxonomyValues(product[field]).includes(value);
}

// محصولاتی که به این صفحه‌ی taxonomy تعلق دارند
export function filterByTaxonomy(products, category, type, value) {
  return (products || []).filter(
    (p) =>
      p &&
      p.deleted !== true &&
      resolveCategoryId(p.category) === category &&
      hasTaxonomyValue(p, type, value)
  );
}

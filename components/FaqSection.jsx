function FaqItem({ q, a, open, onToggle }) {
  return (
    <div
      style={{
        background: "var(--surface)",
        border: "1px solid var(--surface2)",
        borderRadius: 14,
        overflow: "hidden",
      }}
    >
      <button
        onClick={onToggle}
        style={{
          width: "100%",
          display: "flex",
          alignItems: "center",
          justifyContent: "space-between",
          gap: 12,
          background: "none",
          border: "none",
          padding: "16px 18px",
          cursor: "pointer",
          textAlign: "right",
        }}
      >
        <span
          style={{
            fontFamily: "Vazirmatn",
            fontWeight: 700,
            fontSize: 14,
            color: "var(--text-hi)",
          }}
        >
          {q}
        </span>

        <ChevronDown
          size={18}
          color="var(--text-mut)"
          style={{
            flexShrink: 0,
            transition: "transform 0.25s ease",
            transform: open ? "rotate(180deg)" : "rotate(0deg)",
          }}
        />
      </button>

      <div
        style={{
          maxHeight: open ? 300 : 0,
          overflow: "hidden",
          transition: "max-height 0.3s ease",
        }}
      >
        <p
          style={{
            margin: 0,
            padding: "0 18px 18px",
            color: "var(--text-lo)",
            fontSize: 13.5,
            lineHeight: 2,
          }}
        >
          {a}
        </p>
      </div>
    </div>
  );
}

